"""Build web/landcover-data.js from the land-cover dashboard's CSV files.

The six CSVs in data/landcover_dashboard/ are copies of the files attached to the
"LakePulse land-cover model runs" dashboard (source and checksums in manifest.json).
This script checks every checksum first and stops if any file differs (fail closed),
then parses each CSV into rows (values kept as text, as the dashboard reads them) and
writes them with each source's description into one JS file that web/landcover.html
loads. Parsing happens here, not in the browser: d3's CSV parser builds code with
`new Function`, which the site's Content-Security-Policy (no 'unsafe-eval') blocks.

Usage: .venv/bin/python scripts/build_landcover_page.py
"""
from __future__ import annotations

import csv as csvlib
import hashlib
import io
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "landcover_dashboard"
OUT = ROOT / "web" / "landcover-data.js"


def main() -> None:
    manifest = json.loads((SRC / "manifest.json").read_text())
    tables, sources = {}, []
    for d in manifest["datasets"]:
        raw = (SRC / d["file"]).read_bytes()
        got = hashlib.sha256(raw).hexdigest()
        if got != d["sha256"]:
            sys.exit(f"{d['file']}: checksum {got[:16]}… does not match manifest {d['sha256'][:16]}…; nothing written")
        reader = csvlib.DictReader(io.StringIO(raw.decode("utf-8"), newline=""))
        tables[d["id"]] = {"columns": reader.fieldnames, "rows": [dict(r) for r in reader]}
        sources.append({k: d.get(k) for k in ("id", "title", "description", "updated", "sha256")})
    payload = {"source_artifact": manifest["source_artifact"], "copied_on": manifest["copied_on"],
               "sources": sources, "tables": tables}
    OUT.write_text("// Generated by scripts/build_landcover_page.py from data/landcover_dashboard/. Do not edit.\n"
                   "window.LC_DATA = " + json.dumps(payload, ensure_ascii=False) + ";\n")
    print(f"checked {len(sources)} files; wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
