"""Run the trend analysis and build the web page's data file.

Usage: .venv/bin/python scripts/run_analysis.py
Reads data/lake_trend_table.csv; writes data/results/{season_means,trends,correlations}.csv,
data/results/drift.json and web/site_data.js.
"""
from __future__ import annotations

import json
import math
import sys
from datetime import date
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from lakepulse import analysis, schema  # noqa: E402
from lakepulse import variables as V  # noqa: E402

PRACTICE = "practice_lake"


def _clean(o):
    if isinstance(o, float) and not math.isfinite(o):
        return None
    if isinstance(o, dict):
        return {k: _clean(v) for k, v in o.items()}
    if isinstance(o, list):
        return [_clean(v) for v in o]
    if hasattr(o, "item"):
        return _clean(o.item())
    return o


def lakes_meta() -> dict:
    regions = json.loads((ROOT / "data" / "geo" / "study_regions.json").read_text())
    s = regions["simcoe_on"]
    wpc = s["water_pixel_check"]
    return {
        "simcoe_on": {
            "name": "Lake Simcoe, Ontario",
            "kind": "real",
            "sample_point": s["sample_point"],
            "facts": [
                f"Lake surface about 722 km² (outline from the Ontario Hydro Network: {s['ohn_area_km2']:.1f} km²).",
                f"Model catchment 2,990 km² (lake twin catchment areas file; recorded there without a registry source).",
                f"Lake temperature uses {wpc['clean_cells_after_margin']} MODIS 1 km water cells that sit at least "
                f"{wpc['shore_margin_m']:.0f} m from shore.",
                f"Catchment variables use a box around the catchment ({s['catchment_bbox_area_km2']:.0f} km², about twice "
                f"the {s['catchment_unit_area_km2']:.0f} km² of the watershed units inside it).",
            ],
            "attribution": s["lake_outline_attribution"],
        },
        PRACTICE: {
            "name": "Practice Lake (made-up data)",
            "kind": "practice",
            "sample_point": None,
            "facts": [
                "This lake does not exist. Its numbers were generated by a computer so you can practise.",
                "Its surface temperature was built with a rise of 0.5 °C per decade; its precipitation was built with no trend.",
            ],
            "attribution": None,
        },
    }


def pick_demos(trends: pd.DataFrame) -> list[dict]:
    ok = trends[trends["status"].eq("ok") & trends["role"].isin(["lake", "driver"])]
    real = ok[ok["lake"].ne(PRACTICE)]
    pool = real if (real["significant"].any() and (~real["significant"]).any()) else ok[ok["lake"].eq(PRACTICE)]
    demos = []
    sig = pool[pool["significant"]].assign(_main=lambda d: d["variable"].ne("lake_skin_temp")).sort_values(["_main", "mann_kendall_p"])
    non = pool[~pool["significant"]].sort_values("mann_kendall_p", ascending=False)
    for kind, frame in (("significant", sig), ("not significant", non)):
        if frame.empty:
            continue
        r = frame.iloc[0]
        demos.append({
            "kind": kind, "lake": r["lake"], "variable": r["variable"], "source": r["source"],
            "title": f"{'A real trend' if kind == 'significant' else 'A wiggle, not a trend'}: {r['label']}",
            "practice": bool(r["lake"] == PRACTICE),
        })
    return demos


def main() -> None:
    table = schema.read(ROOT / "data" / "lake_trend_table.csv")
    seasonal = analysis.season_means(table)
    trends = analysis.trend_table(seasonal)
    corr = analysis.correlations(seasonal)
    drift = {lake: analysis.drift_check(seasonal, lake) for lake in sorted(table["lake"].unique())}

    res = ROOT / "data" / "results"
    res.mkdir(parents=True, exist_ok=True)
    seasonal.to_csv(res / "season_means.csv", index=False)
    trends.to_csv(res / "trends.csv", index=False)
    corr.to_csv(res / "correlations.csv", index=False)
    (res / "drift.json").write_text(json.dumps(_clean(drift), indent=2) + "\n")

    series = {}
    for (lake, var, src), g in table.groupby(["lake", "variable", "source"]):
        g = g.sort_values("date")
        s = seasonal[(seasonal.lake == lake) & (seasonal.variable == var) & (seasonal.source == src)]
        tr = trends[(trends.lake == lake) & (trends.variable == var) & (trends.source == src)]
        series.setdefault(lake, {}).setdefault(var, []).append({
            "source": src,
            "tier": g["tier"].iloc[0],
            "points": [[d.strftime("%Y-%m-%d"), v] for d, v in zip(g["date"], g["value"])],
            "season": [[int(y), round(float(v), 4)] for y, v in zip(s["year"], s["value"])],
            "trend": _clean(tr.iloc[0].to_dict()) if len(tr) else None,
        })

    site = {
        "generated": date.today().isoformat(),
        "season_months": list(analysis.SEASON_MONTHS),
        "min_seasons": __import__("lakepulse.stats", fromlist=["MIN_POINTS"]).MIN_POINTS,
        "cause_caveat": analysis.CAUSE_CAVEAT,
        "spurious_trend_note": analysis.SPURIOUS_TREND_NOTE,
        "expectations": {k: v for k, v in analysis.load_expectations().items() if k != "pairs"},
        "lakes": lakes_meta(),
        "variables": {k: {"label": v.label, "unit": v.unit, "tier": v.tier, "source": v.source, "scope": v.scope,
                          "frequency": v.frequency, "definition": v.definition, "notes": list(v.notes),
                          "role": v.role, "accuracy": v.accuracy} for k, v in V.VARIABLES.items()},
        "series": series,
        "correlations": _clean(corr.to_dict(orient="records")),
        "drift": _clean(drift),
        "demos": pick_demos(trends),
    }
    js = "window.SITE_DATA = " + json.dumps(_clean(site), ensure_ascii=False) + ";\n"
    (ROOT / "web" / "site_data.js").write_text(js)
    n_sig = int(trends["significant"].sum())
    print(f"season means: {len(seasonal)} | trend series: {len(trends)} ({n_sig} significant) | "
          f"correlations: {len(corr)} | wrote web/site_data.js ({len(js):,} bytes)")
    print(trends[["lake", "variable", "n_seasons", "slope_per_decade", "mann_kendall_p", "significant", "accuracy_verdict"]].to_string(index=False))
    print("\ncorrelation pairs (all tested, including those that show nothing):")
    print(corr[["lake", "x", "y", "status", "n", "r_raw", "p_raw", "r_detrended", "p_detrended", "expected_sign", "found_raw", "found_detrended"]].to_string(index=False))


if __name__ == "__main__":
    main()
